            # ... (বাকি বেটিং লজিক আপনার আগের কোডের মতোই থাকবে, যেহেতু ওগুলো UI বেসড ক্লিক)
            # এখানে কোড কাটা হলো কারণ আপনার আগের কোডেই সবকিছু ঠিক আছে।
            # আপনি চাইলে আগের কোডের বাকি অংশ কপি করে এখানে বসাতে পারেন।
            
